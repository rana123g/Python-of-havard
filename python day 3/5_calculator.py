# Learning about integers simple numbers like 1 or 2 they can be positive or negative
x = int(input("Enter your first number: "))
y = int(input("Enter your second number: "))
print(x + y) # this bascially adds the two numbers together and prints the result
print(x - y) # This bascially subtracts the two numbers and prints the result
print(x * y) # this bascially multiplies the two numbers and prints the result
print(x / y) # This bascially divides the two numbers and prints the result
print(x % y) # This bascially divides the two numbers and prints the remainder of the result
